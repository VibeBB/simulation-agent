"""Device-API stubs for the mruby/c Emscripten leg.

When the UX-authored ``*.mruby-api.json`` declares device classes, sim
generates ``sim_api_stub.{c,h}`` — permissive C bindings that register
the same class/method surface in the VM, log each call to the transcript
(``API <Class>.<method>(<args>)`` so ``expect`` lines can assert on
behavior), honor the spec's ``system_task`` vm_id gate, and return
deterministic neutral values of the declared type. Instance classes get
real ``mrbc_instance_new`` objects with zeroed data, so UX `.rb` code
exercises object lifecycles off-target.

The spec fields sim reads mirror ``firmware.mruby_api``; the JSON is
the contract, never shared code. Unknown spec fields are ignored so a
newer UX schema keeps working with an older sim.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


class _Model(BaseModel):
    model_config = ConfigDict(extra="ignore")


class StubParam(_Model):
    name: str = ""
    type: str = "int"
    required: bool = True
    max_len: int = 0
    enum: list[str] = Field(default_factory=lambda: list[str]())


class StubReturn(_Model):
    type: str = "nil"
    cap: int = 0


class StubMethod(_Model):
    name: str
    doc: str = ""
    params: list[StubParam] = Field(default_factory=lambda: list[StubParam]())
    kwargs: list[StubParam] = Field(default_factory=lambda: list[StubParam]())
    rest_kwargs: bool = False
    block: str = "none"
    returns: StubReturn = Field(default_factory=StubReturn)
    access: str = "any"
    arg_errors: str = "raise"
    handler: str = ""


class StubInstance(_Model):
    data_size: int = 16
    constructor: str = ""
    destructor: str = ""


class StubConst(_Model):
    name: str
    value: int | float | bool | str


class StubClass(_Model):
    name: str
    kind: str = "class"
    outer: str = ""
    super: str = ""
    doc: str = ""
    constants: list[StubConst] = Field(default_factory=lambda: list[StubConst]())
    methods: list[StubMethod] = Field(default_factory=lambda: list[StubMethod]())
    init: str = ""
    instance: StubInstance | None = None


class StubSystemTask(_Model):
    vm_id: int = 1


class MrubyApiStubSpec(_Model):
    schema_version: Literal[1] = 1
    artifact_kind: Literal["mruby_api"] = "mruby_api"
    product: str = ""
    symbols: list[dict[str, str]] = Field(default_factory=lambda: list[dict[str, str]]())
    classes: list[StubClass] = Field(default_factory=lambda: list[StubClass]())
    system_task: StubSystemTask | None = None
    expert_define: str = ""


_FUNC_SAFE = re.compile(r"[^A-Za-z0-9_]")
_HEADER = """/* Auto-generated by `sim mrubyc`; do not edit by hand.
 * api spec: {spec}
 * Deterministic device-API stubs — transcript logging, neutral returns.
 */
"""


def _c_ident(name: str) -> str:
    return _FUNC_SAFE.sub("_", name.replace("?", "_p").replace("!", "_b"))


def _fmt_value(param_type: str, expr: str) -> tuple[str, str]:
    """Printf format + expression for a decoded mrb_value."""
    return {
        "int": ("%lld", f"(long long){expr}.i"),
        "float": ("%g", f"(double)mrbc_float({expr})"),
        "bool": ("%s", f'({expr}.tt == MRBC_TT_TRUE ? "true" : "false")'),
        "symbol": ("%s", f"mrbc_symid_to_str({expr}.sym_id)"),
        "string": ("%s", f"mrbc_string_cstr(&{expr})"),
        "array<int>": (
            "%u",
            f"(unsigned)({expr}.tt == MRBC_TT_ARRAY ? {expr}.array->n_stored : 0U)",
        ),
    }[param_type]


def _emit_log_args(method: StubMethod, uses_kw: bool) -> tuple[str, list[str]]:
    """Format string + arg expressions for the transcript line."""
    fmt: list[str] = []
    args: list[str] = []
    for index, param in enumerate(method.params, start=1):
        f, e = _fmt_value(param.type, f"v[{index}]")
        fmt.append(f"{param.name}={f}")
        args.append(e)
    if uses_kw:
        for kw in method.kwargs:
            f, e = _fmt_value(kw.type, kw.name)
            fmt.append(f"{kw.name}={f}")
            args.append(e)
    if method.rest_kwargs:
        fmt.append("rest=%d")
        args.append("(int)(rest.tt == MRBC_TT_HASH ? mrbc_hash_size(&rest) : 0)")
    if method.block != "none":
        fmt.append("block=%s")
        args.append('(blk != 0 ? "given" : "none")')
    return ", ".join(fmt), args


def _emit_return(
    returns: StubReturn, spec: MrubyApiStubSpec, cls_name: str, method_name: str
) -> list[str]:
    t = returns.type
    if t == "bool":
        return ["\tSET_TRUE_RETURN();"]
    if t == "int":
        return ["\tSET_INT_RETURN(0);"]
    if t == "float":
        return ["\tSET_FLOAT_RETURN(0.0);"]
    if t == "symbol" and spec.symbols:
        first = spec.symbols[0]["name"]
        return [
            "\tdo {",
            f'\t\tmrb_value ret = mrbc_symbol_value(mrbc_str_to_symid("{first}"));',
            "\t\tSET_RETURN(ret);",
            "\t} while (0);",
        ]
    if t == "string":
        return [
            f'\tmrb_value ret = mrbc_string_new_cstr(vm, "{cls_name}.{method_name}");',
            "\tSET_RETURN(ret);",
        ]
    if t.startswith("array<"):
        n = returns.cap or 1
        elem = "mrbc_integer_value(0)" if t == "array<int>" else "mrbc_float_value(0, 0.0)"
        return [
            "\tdo {",
            f"\t\tmrb_value ret = mrbc_array_new(vm, {n}u);",
            "\t\tmrb_value zero = " + elem + ";",
            f"\t\tfor (int _i = 0; _i < {n}; _i++) {{",
            "\t\t\tmrbc_array_set(&ret, _i, &zero);",
            "\t\t}",
            "\t\tSET_RETURN(ret);",
            "\t} while (0);",
        ]
    return ["\tSET_NIL_RETURN();"]


_TT_CHECK = {
    "int": "MRBC_TT_INTEGER",
    "float": "MRBC_TT_FLOAT",
    "bool": "(MRBC_TT_TRUE == %s.tt || MRBC_TT_FALSE == %s.tt)",
    "symbol": "MRBC_TT_SYMBOL",
    "string": "MRBC_TT_STRING",
    "array<int>": "MRBC_TT_ARRAY",
}


def _emit_param_decode(cls: StubClass, method: StubMethod) -> list[str]:
    """Positional-arg decode, firmware's do-while(0) idiom."""
    if not method.params:
        return []
    out = [
        "",
        "\t// ==============================",
        "\tint ok = 0;",
        "\tdo {",
    ]
    checks: list[str] = []
    for index, param in enumerate(method.params, start=1):
        tt = _TT_CHECK.get(param.type)
        if param.required:
            out.append(f"\t\tif (argc < {index}) break;")
        else:
            out.append(f"\t\tif (argc < {index}) continue;")
        if tt is not None:
            if "%s" in tt:
                checks.append("\t\tif (!" + (tt % (f"v[{index}]", f"v[{index}]")) + ") break;")
            else:
                checks.append(f"\t\tif ({tt} != v[{index}].tt) break;")
    out += checks
    out += ["\t\tok = 1;", "\t} while (0);"]
    if method.arg_errors == "raise":
        out += [
            "\tif (!ok) {",
            '\t\tmrbc_raise(vm, MRBC_CLASS(ArgumentError), "'
            f'{cls.name}.{method.name}: invalid argument");',
            "\t\treturn;",
            "\t}",
        ]
    else:
        out += [
            "\tif (!ok) {",
            "\t\tSET_NIL_RETURN();",
            "\t}",
        ]
    out.append("\t// ==============================")
    return out


def _emit_method(cls: StubClass, method: StubMethod, spec: MrubyApiStubSpec) -> list[str]:
    func = f"sim_api_{_c_ident(cls.name)}_{_c_ident(method.name)}"
    out = [
        "/**",
        " * @brief Stub for "
        f"{cls.name}.{method.name} — logs the call, returns {method.returns.type}",
        " *",
        " * @param vm The mruby/c VM instance",
        " * @param v The value array",
        " * @param argc The argument count",
        " */",
        f"static void {func}(mrb_vm *vm, mrb_value *v, int argc) {{",
    ]
    uses_kw = bool(method.kwargs) or method.rest_kwargs
    uses_block = method.block != "none"
    if uses_block:
        out.append("\tmrb_value *blk = 0;")
    if not (method.params or uses_kw or uses_block):
        out.append("\t(void)argc;")
    if method.access == "system_task" and spec.system_task is not None:
        out += [
            "",
            "\t/* access gate: system task only (mirrors firmware behavior) */",
            f"\tif (vm->vm_id != {spec.system_task.vm_id}u) {{",
            "\t\tSET_NIL_RETURN();",
            "\t}",
        ]
    out += _emit_param_decode(cls, method)
    if uses_kw:
        out += [
            "",
            "\t// ==============================",
        ]
        if method.kwargs:
            names = ", ".join(p.name for p in method.kwargs)
            out.append(f"\tMRBC_KW_ARG({names});")
        if method.rest_kwargs:
            out.append("\tMRBC_KW_DICT(rest);")
        if method.kwargs:
            mand = "".join(
                f"\t\tif (!MRBC_KW_MANDATORY({p.name})) break;\n"
                for p in method.kwargs
                if p.required
            )
            out += [
                "\tdo {",
                mand + "\t\tif (!MRBC_KW_END()) break;",
                "\t} while (0);",
                f"\tMRBC_KW_DELETE({', '.join(p.name for p in method.kwargs)});",
                "\tif (mrbc_israised(vm)) {",
                "\t\treturn;",
                "\t}",
            ]
        out.append("\t// ==============================")
    if uses_block:
        out += [
            "",
            "\t/* trailing block: v[argc+1], or v[argc+2] after a kw-hash */",
            "\tif (MRBC_TT_PROC == v[argc + 1].tt) {",
            "\t\tblk = &v[argc + 1];",
            "\t} else if (MRBC_TT_HASH == v[argc + 1].tt &&",
            "\t\t\tMRBC_TT_PROC == v[argc + 2].tt) {",
            "\t\tblk = &v[argc + 2];",
            "\t}",
        ]
    fmt, args = _emit_log_args(method, uses_kw)
    sig_args = "" if not args else ", " + ", ".join(args)
    out += [
        "",
        f'\tprintf("API {cls.name}.{method.name}({fmt})\\n"{sig_args});',
        *_emit_return(method.returns, spec, cls.name, method.name),
        "}",
        "",
    ]
    return out


def _emit_class(cls: StubClass, spec: MrubyApiStubSpec) -> list[str]:
    out: list[str] = []
    if cls.instance is not None:
        out += [
            f"static void sim_api_{_c_ident(cls.name)}_dtor(mrb_value *v) {{",
            "\t(void)v;\t/* stub: data is zeroed at construction */",
            "}",
            "",
            f"static void sim_api_{_c_ident(cls.name)}_new(mrb_vm *vm, mrb_value *v, int argc) {{",
            "\t(void)argc;",
            f"\t*v = mrbc_instance_new(vm, v[0].cls, {cls.instance.data_size}u);",
            f"\tmemset(v->instance->data, 0, {cls.instance.data_size}u);",
            "}",
            "",
        ]
    for method in cls.methods:
        out += _emit_method(cls, method, spec)
    return out


def _class_define_lines(cls: StubClass, spec: MrubyApiStubSpec) -> list[str]:
    stem = _c_ident(cls.name)
    out = [
        f"\t/* ---- {cls.name} ({cls.kind}) ---- */",
    ]
    known = {c.name for c in spec.classes}
    super_expr = (
        f"{_c_ident(cls.super)}_cls" if cls.super and cls.super in known else "mrbc_class_object"
    )
    if cls.outer:
        outer_ref = f"{_c_ident(cls.outer)}_cls"
        if cls.kind == "module":
            out.append(
                f'\t{cls.name}_cls = mrbc_define_module_under(0, {outer_ref}, "{cls.name}");'
            )
        else:
            out.append(
                f"\t{cls.name}_cls = mrbc_define_class_under("
                f'0, {outer_ref}, "{cls.name}", {super_expr});'
            )
    elif cls.kind == "module":
        out.append(f'\t{cls.name}_cls = mrbc_define_module(0, "{cls.name}");')
    else:
        out.append(f'\t{cls.name}_cls = mrbc_define_class(0, "{cls.name}", {super_expr});')
    for const in cls.constants:
        value = (
            f'mrbc_string_new_cstr(0, "{const.value}")'
            if isinstance(const.value, str)
            else (
                "mrbc_integer_value(1)"
                if const.value is True
                else "mrbc_integer_value(0)"
                if const.value is False
                else f"mrbc_float_value(0, {const.value})"
                if isinstance(const.value, float)
                else f"mrbc_integer_value({const.value})"
            )
        )
        out += [
            "\t{",
            f"\t\tmrb_value k_{_c_ident(const.name)} = {value};",
            f"\t\t(void)mrbc_set_class_const({cls.name}_cls, "
            f'mrbc_str_to_symid("{const.name}"), &k_{_c_ident(const.name)});',
            "\t}",
        ]
    if cls.instance is not None:
        out += [
            f"\tmrbc_define_destructor({cls.name}_cls, sim_api_{stem}_dtor);",
            f'\tmrbc_define_method(0, {cls.name}_cls, "new", sim_api_{stem}_new);',
        ]
    for method in cls.methods:
        guard = (
            f"#if defined({spec.expert_define})"
            if method.access == "expert" and spec.expert_define
            else ""
        )
        if guard:
            out.append(guard)
        out.append(
            f'\tmrbc_define_method(0, {cls.name}_cls, "{method.name}", '
            f"sim_api_{_c_ident(cls.name)}_{_c_ident(method.name)});"
        )
        if guard:
            out.append(f"#endif /* {guard} */")
    return out


def _sorted_classes(classes: list[StubClass]) -> list[StubClass]:
    """Topological order so outer/super classes are defined first."""
    by_name = {c.name: c for c in classes}
    ordered: list[StubClass] = []
    seen: set[str] = set()

    def visit(cls: StubClass) -> None:
        if cls.name in seen:
            return
        seen.add(cls.name)
        for dep in (cls.outer, cls.super):
            parent = by_name.get(dep)
            if dep and parent is not None:
                visit(parent)
        ordered.append(cls)

    for cls in classes:
        visit(cls)
    return ordered


def _uses_argument_error(spec: MrubyApiStubSpec) -> bool:
    return any(m.arg_errors == "raise" for c in spec.classes for m in c.methods)


def render_stub(spec: MrubyApiStubSpec, spec_rel: str) -> dict[str, str]:
    """Generated ``sim_api_stub.{h,c}`` for a device API spec."""
    cls_names = [_c_ident(c.name) for c in spec.classes]
    header = [
        _HEADER.format(spec=spec_rel),
        "#ifndef SIM_API_STUB_H",
        "#define SIM_API_STUB_H",
        "",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "/**",
        " * @brief Registers every stub class/method in the VM",
        " *",
        " * @return 0 on success, -1 on failure",
        " */",
        "int sim_api_define(void);",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "#endif /* SIM_API_STUB_H */",
        "",
    ]
    source = [
        _HEADER.format(spec=spec_rel),
        '#include "sim_api_stub.h"',
        "",
        "#include <stdio.h>",
        "#include <string.h>",
        "",
        '#include "mrubyc.h"',
        "",
    ]
    if _uses_argument_error(spec):
        source += [
            "extern struct RBuiltinNoMethodClass mrbc_class_ArgumentError;",
            "",
        ]
    source += [
        *[f"mrbc_class *{n}_cls;" for n in cls_names],
        "",
    ]
    ordered = _sorted_classes(spec.classes)
    for cls in ordered:
        source += _emit_class(cls, spec)
    source += [
        "/**",
        " * @brief Registers every stub class/method in the VM",
        " *",
        " * @return 0 on success, -1 on failure",
        " */",
        "int sim_api_define(void) {",
    ]
    for cls in ordered:
        source += _class_define_lines(cls, spec)
    source += ["\treturn 0;", "}", ""]
    return {
        "sim_api_stub.h": "\n".join(header),
        "sim_api_stub.c": "\n".join(source),
    }


def stub_problems(spec_path: Path, workspace: Path) -> list[str]:
    """Validate the spec path the brief points at."""
    problems: list[str] = []
    resolved = workspace / spec_path
    if not resolved.is_file():
        return [f"api spec {spec_path} missing"]
    try:
        MrubyApiStubSpec.model_validate_json(resolved.read_text(encoding="utf-8"))
    except ValueError as exc:
        problems.append(f"{spec_path.name} invalid: {exc}")
    return problems


def load_stub_spec(spec_path: Path, workspace: Path) -> MrubyApiStubSpec:
    resolved = workspace / spec_path
    return MrubyApiStubSpec.model_validate_json(resolved.read_text(encoding="utf-8"))
