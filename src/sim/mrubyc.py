"""mruby/c Emscripten leg: run UX ``.rb`` sources in the mruby/c WASM VM.

Mirrors the firmware/dashboard toolchain: ``mrbc -B`` compiles each authored
Ruby source into C bytecode, a generated shim exports ``mruby_ux_init`` and
``mruby_ux_run``, emcc links it with the mruby/c core and the upstream
``hal/emscripten`` backend, and Node runs every task to completion. Missing
tools report ``unknown`` per the brief invariants; build or VM failures are
deterministic ``fail`` checks.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
from pathlib import Path

from .brief import MrubycSection
from .gates import GateCheck, check
from .workspace import workspace_path

MRUBYC_DIR_ENV = "SIM_MRUBYC_DIR"
_VALID_STEM = re.compile(r"[^A-Za-z0-9_]")

_SHIM_TEMPLATE = """/* generated by sim.mrubyc — do not edit */
#include <stdint.h>
#include <stdio.h>
#include "mrubyc.h"

{externs}

static uint8_t memory_pool[{memory_size}];

__attribute__((used)) int
mruby_ux_init(void)
{{
	mrbc_init_alloc(memory_pool, sizeof(memory_pool));
	mrbc_init_global();
	mrbc_init_class();
	return 0;
}}

__attribute__((used)) int
mruby_ux_run(void)
{{
{tasks}
	mrbc_run();
	return 0;
}}
"""

_RUNNER = """import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const { default: createModule } = await import(pathToFileURL(process.argv[2]).href);
const module = await createModule();
assert.equal(await module._mruby_ux_init(), 0, 'mruby_ux_init failed');
assert.equal(await module._mruby_ux_run(), 0, 'mruby_ux_run failed');
"""


def _tools() -> list[str]:
    return [name for name in ("emcc", "node", "mrbc") if shutil.which(name) is None]


def _compile(
    section: MrubycSection, workspace: Path, out_dir: Path
) -> tuple[list[Path], list[str], str | None]:
    mrubyc_dir = Path(os.environ.get(MRUBYC_DIR_ENV, "/opt/mrubyc"))
    core_dir = mrubyc_dir / "src"
    hal_dir = mrubyc_dir / "hal" / "emscripten"
    if not core_dir.is_dir() or not (hal_dir / "hal.c").is_file():
        return [], [], f"mruby/c tree not found under {mrubyc_dir} (set {MRUBYC_DIR_ENV})"

    out_dir.mkdir(parents=True, exist_ok=True)
    bytecode: list[Path] = []
    symbols: list[str] = []
    for index, rel in enumerate(section.sources):
        source = workspace_path(rel, workspace)
        if not source.is_file():
            return [], [], f"ruby source missing: {rel}"
        symbol = _VALID_STEM.sub("_", source.stem) or f"ux_{index}"
        if symbol in symbols:
            symbol = f"{symbol}_{index}"
        symbols.append(symbol)
        out_c = out_dir / f"{symbol}.c"
        proc = subprocess.run(
            [
                str(shutil.which("mrbc")),
                "-B",
                symbol,
                "--remove-lv",
                "-o",
                str(out_c),
                str(source),
            ],
            capture_output=True,
            text=True,
            timeout=120,
            check=False,
        )
        if proc.returncode != 0 or not out_c.is_file():
            detail = proc.stderr.strip() or "mrbc -B failed"
            return [], [], f"{rel}: {detail}"
        bytecode.append(out_c)

    externs = "\n".join(f"extern const uint8_t {symbol}[];" for symbol in symbols)
    tasks = "\n".join(
        f"\tif (mrbc_create_task({symbol}, 0) == 0) {{\n"
        f'\t\tputs("mruby task create failed: {symbol}");\n'
        f"\t\treturn 1;\n\t}}"
        for symbol in symbols
    )
    shim = out_dir / "mruby_ux_main.c"
    shim.write_text(
        _SHIM_TEMPLATE.format(externs=externs, tasks=tasks, memory_size=section.memory_size),
        encoding="utf-8",
    )
    runner = out_dir / "run-mruby.mjs"
    runner.write_text(_RUNNER, encoding="utf-8")

    module = out_dir / "module.mjs"
    core_sources = [path for path in core_dir.glob("*.c") if path.name != "hal.c"]
    argv = [
        str(shutil.which("emcc")),
        "-O2",
        f"-I{core_dir}",
        f"-I{hal_dir}",
        *[str(path) for path in sorted(core_sources)],
        str(hal_dir / "hal.c"),
        *[str(path) for path in bytecode],
        str(shim),
        "--no-entry",
        "-sMODULARIZE=1",
        "-sEXPORT_ES6=1",
        "-sEXPORT_NAME=createModule",
        "-sALLOW_MEMORY_GROWTH=1",
        "-sASYNCIFY",
        "-s",
        "EXPORTED_FUNCTIONS=['_mruby_ux_init','_mruby_ux_run','_malloc','_free']",
        "-o",
        str(module),
    ]
    proc = subprocess.run(
        argv, cwd=workspace, capture_output=True, text=True, timeout=600, check=False
    )
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout).strip() or "emcc failed"
        return [], [], detail
    return [module], symbols, None


def run_mrubyc(section: MrubycSection, workspace: Path, out_dir: Path) -> list[GateCheck]:
    missing = _tools()
    if missing:
        return [
            check(
                "mrubyc.tools",
                "mrubyc",
                "unknown",
                f"required tool not found: {', '.join(missing)}",
            )
        ]
    built, _symbols, error = _compile(section, workspace, out_dir / "mrubyc")
    if error is not None or not built:
        return [
            check("mrubyc.build", "mrubyc", "fail", error or "no module produced"),
        ]
    module = built[0]
    proc = subprocess.run(
        [str(shutil.which("node")), str(out_dir / "mrubyc" / "run-mruby.mjs"), str(module)],
        cwd=workspace,
        capture_output=True,
        text=True,
        timeout=300,
        check=False,
    )
    transcript = (proc.stdout + proc.stderr).strip()
    checks = [
        check(
            "mrubyc.vm",
            "mrubyc",
            "pass" if proc.returncode == 0 else "fail",
            transcript or f"exit code {proc.returncode}",
        )
    ]
    for needle in section.expect:
        verdict = "pass" if needle in transcript else "fail"
        detail = "contains" if needle in transcript else "missing"
        checks.append(
            check(
                f"mrubyc.transcript[{needle}]",
                "mrubyc",
                verdict,
                f"transcript {detail} {needle!r}",
            )
        )
    return checks
